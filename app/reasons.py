def label_of(code: str) -> str:
    return _LABELS.get(code, code)


def all_codes() -> dict:
    return dict(_LABELS)


def group_of(code: str) -> str:
    for name, codes in GROUPS.items():
        if code in codes:
            return name
    return "other"


def code_table() -> list:
    return [{"code": code, "label": label, "group": group_of(code)}
            for code, label in _LABELS.items()]
